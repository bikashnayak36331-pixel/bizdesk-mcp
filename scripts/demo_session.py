"""Record a real BizDesk session for the README.

Starts the actual `bizdesk-mcp` command over stdio (the same way Claude Desktop does),
loads the fictional demo data into a temporary database, calls tools in a short story,
and saves:

  docs/demo-session.md   - every request and the exact response text
  docs/demo-session.svg  - the same session as a terminal screenshot
  docs/images/invoice.png, docs/images/quote.png - pages of the exported PDFs

Run:  python scripts/demo_session.py
"""

from __future__ import annotations

import json
import subprocess
import sys
import tempfile
from pathlib import Path

import anyio
from mcp import Client
from mcp.client.stdio import StdioServerParameters
from rich.console import Console
from rich.panel import Panel
from rich.syntax import Syntax
from rich.table import Table

ROOT = Path(__file__).resolve().parent.parent
DOCS = ROOT / "docs"


def payload(result):
    if result.is_error:
        return {"error": result.content[0].text}
    sc = result.structured_content or {}
    return sc.get("result", sc)


async def run(tmp: Path) -> None:
    db, pdfs = tmp / "demo.db", tmp / "pdfs"
    subprocess.run([sys.executable, "-m", "bizdesk_mcp", "--db", str(db), "--seed-demo"], check=True)
    params = StdioServerParameters(
        command=sys.executable, args=["-m", "bizdesk_mcp", "--db", str(db), "--output-dir", str(pdfs)]
    )
    console = Console(record=True, width=104, highlight=False)
    md: list[str] = [
        "# BizDesk MCP: a recorded session",
        "",
        "Real requests and responses from `bizdesk-mcp` over stdio, with the fictional demo data "
        "(`--seed-demo`). Generated by `scripts/demo_session.py`.",
        "",
    ]

    async with Client(params) as c:
        tools = (await c.list_tools()).tools
        console.print(Panel.fit(f"[bold]bizdesk-mcp[/] connected over stdio · {len(tools)} tools", style="green"))
        md += [f"Connected over stdio. {len(tools)} tools: " + ", ".join(f"`{t.name}`" for t in tools), ""]

        async def step(title: str, tool: str, args: dict, show=None):
            res = payload(await c.call_tool(tool, args))
            console.rule(f"[bold cyan]{title}")
            console.print(f"[dim]call[/] [bold]{tool}[/] {json.dumps(args)}")
            if show:
                show(res)
            else:
                console.print(Syntax(json.dumps(res, indent=2), "json", theme="ansi_dark", word_wrap=True))
            md.extend(
                [
                    f"## {title}",
                    "",
                    f"`{tool}` `{json.dumps(args)}`",
                    "",
                    "```json",
                    json.dumps(res, indent=2),
                    "```",
                    "",
                ]
            )
            return res

        def clients_table(rows):
            t = Table(show_edge=False, header_style="bold")
            for col in ("id", "client", "invoiced", "paid", "outstanding", "overdue"):
                t.add_column(col, justify="right" if col not in ("client",) else "left")
            for r in rows:
                t.add_row(
                    str(r["id"]),
                    r["company"] or r["name"],
                    r["total_invoiced"],
                    r["total_paid"],
                    r["outstanding"],
                    str(r["overdue_invoices"]),
                )
            console.print(t)

        def overdue_table(rep):
            ages = " · ".join(f"{k}: {v}" for k, v in rep["by_age"].items())
            console.print(
                f"Total overdue: [bold red]{rep['total_overdue']}[/] across {rep['overdue_invoices']} invoices ({ages})"
            )
            t = Table(show_edge=False, header_style="bold")
            for col in ("invoice", "client", "due", "days late", "balance"):
                t.add_column(col)
            for r in rep["invoices"]:
                t.add_row(r["number"], r["client"], r["due_date"], str(r["days_overdue"]), r["balance_due"])
            console.print(t)

        def reminder(r):
            console.print(
                Panel(
                    f"[bold]To:[/] {r['to']}\n[bold]Subject:[/] {r['subject']}\n\n{r['body']}",
                    title="draft email (not sent)",
                    expand=False,
                )
            )

        def doc_summary(d):
            console.print(
                f"[bold]{d['number']}[/] ({d['status']}) for {d['client']['company']}: "
                f"subtotal {d['subtotal']} + tax {d['tax']} = [bold]{d['total']}[/]"
                + (f" · balance due {d['balance_due']}" if d["kind"] == "invoice" else "")
            )

        def revenue(r):
            t = Table(show_edge=False, header_style="bold")
            for col in ("month", "invoices", "invoiced", "collected"):
                t.add_column(col, justify="right")
            for m in r["by_month"]:
                t.add_row(m["month"], str(m["invoices"]), m["invoiced"], m["collected"])
            console.print(t)
            console.print(
                f"Invoiced {r['invoiced']} · collected {r['collected']} · "
                f"outstanding now [bold]{r['outstanding_now']}[/]"
            )

        clients = await step("Who are my clients and who owes money?", "find_clients", {}, clients_table)
        await step("What is overdue?", "overdue_report", {}, overdue_table)
        await step(
            "Draft a reminder for the oldest one",
            "draft_payment_reminder",
            {"invoice_number": "INV-0004", "tone": "firm"},
            reminder,
        )
        dental = next(x for x in clients if x["company"] == "Maple Street Dental")
        quote = await step(
            "Quote a new job",
            "create_quote",
            {
                "client_id": dental["id"],
                "items": [
                    {"description": "After-hours deep clean, 2 treatment rooms", "quantity": 2, "unit_price": 185},
                    {"description": "Sterilisation-room disinfection", "quantity": 1, "unit_price": 120},
                ],
                "notes": "Scheduled for a Saturday.",
            },
            doc_summary,
        )
        inv = await step(
            "Client accepted: turn the quote into an invoice",
            "convert_quote_to_invoice",
            {"quote_number": quote["number"]},
            doc_summary,
        )
        await step(
            "They paid a deposit",
            "record_payment",
            {"invoice_number": inv["number"], "amount": 200, "method": "card"},
            doc_summary,
        )
        await step("How is the business doing?", "revenue_report", {}, revenue)
        pdf = await step(
            "Export the invoice as a PDF",
            "export_pdf",
            {"number": inv["number"]},
            lambda r: console.print(f"Saved [bold]{Path(r['path']).name}[/] ({r['bytes']:,} bytes)"),
        )
        qpdf = payload(await c.call_tool("export_pdf", {"number": quote["number"]}))

    DOCS.mkdir(exist_ok=True)
    (DOCS / "images").mkdir(exist_ok=True)
    (DOCS / "demo-session.md").write_text("\n".join(md).replace(str(tmp), "<demo folder>"))
    console.save_svg(str(DOCS / "demo-session.svg"), title="bizdesk-mcp · recorded session")
    for src, name in ((pdf["path"], "invoice"), (qpdf["path"], "quote")):
        subprocess.run(["pdftoppm", "-r", "110", "-png", "-singlefile", src, str(DOCS / "images" / name)], check=True)
    print("Saved docs/demo-session.md, docs/demo-session.svg, docs/images/invoice.png, docs/images/quote.png")


if __name__ == "__main__":
    with tempfile.TemporaryDirectory() as d:
        anyio.run(run, Path(d))
